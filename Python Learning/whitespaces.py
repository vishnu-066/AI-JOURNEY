# whitespaces


print("vishnu vardhan")    # space between vishnu and vardhan
print("vishnu\tvardhan")   # tab space between vishnu and vardhan
print("vishnu\nvardhan")   # new line between vishnu and vardhan
print("vishnu\vvardhan")   # vertical tab space between vishnu and vardhan
print("vishnu\rvardhan")   # carriage return between vishnu and vardhan
print("vishnu\bvardhan")   # backspace between vishnu and vardhan
print("vishnu\fvardhan")   # form feed between vishnu and vardhan
print("vishnu\vardhan")   # backslash between vishnu and vardhan
print("vishnu\'vardhan")   # single quote between vishnu and vardhan
print("vishnu\"vardhan")   # double quote between vishnu and vardhan
print("vishnu\?vardhan")   # question mark between vishnu and vardhan


